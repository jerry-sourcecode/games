export const skillKeys = skills.map((skill) => skill.key);

export const getSkill = (key: SkillKey): Skill =>
    skills.find((skill) => skill.key === key)!;

/** 抽取不重复的技能候选；候选之间独立随机，允许与另一阶段重叠 */
export function drawSkillCandidates(count = 3): SkillKey[] {
    const pool = [...skillKeys];
    shuffle(pool);
    return pool.slice(0, Math.min(count, pool.length));
}
